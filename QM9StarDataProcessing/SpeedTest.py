conn = sqlite3.connect("DATA/EnthalpyTables.db")
cursor = conn.cursor()

target_smiles = [ # test data generated by google gemini and edited, not concialzed but good for testing because will need to sreaching for nonexisting items
    ""
]

def timer(func):
    def wrapper(*args, **kwargs):
        t1 = time.time()
        result = func(*args, **kwargs)
        t2 = time.time()
        print(f'Function {func.__name__!r} executed in {(t2-t1):.4f}s')
        return result
    return wrapper

@timer
def speedtestCSV(querys):
    # Exact match lookup
    result = []
    for query in querys:
        result.append(CSVForm[CSVForm["SMILES"] == query])
    print(result)

@timer
def speedtestDB(querys):
    result = []
    for query in querys:
        # Query a specific table using a parameterized query (?)
        cursor.execute("SELECT * FROM Radical_0 WHERE SMILES = ?", (query,))
        result.append(cursor.fetchall())

speedtestCSV(target_smiles)
speedtestDB(target_smiles)